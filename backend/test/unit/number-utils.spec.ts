import { parseLocalizedNumber } from '../../src/imports/number-utils';

describe('parseLocalizedNumber', () => {
  const ok: [string, unknown, number][] = [
    ['обычное число', 1250.5, 1250.5],
    ['целое в строке', '1250', 1250],
    ['точка как десятичный разделитель', '1250.50', 1250.5],
    ['запятая как десятичный разделитель', '1250,50', 1250.5],
    ['короткая дробь через запятую', '12,3', 12.3],
    ['пробел как разделитель тысяч', '5 000', 5000],
    ['неразрывный пробел', '5 000', 5000],
    ['тонкий неразрывный пробел', '5 000', 5000],
    ['пробелы и запятая', '1 250,5', 1250.5],
    ['европейский формат 1.250,50', '1.250,50', 1250.5],
    ['американский формат 1,250.50', '1,250.50', 1250.5],
    ['несколько запятых — разделители тысяч', '1,250,000', 1250000],
    ['несколько точек — разделители тысяч', '1.250.000', 1250000],
    ['отрицательное число', '-5', -5],
    ['ноль', '0', 0],
  ];

  for (const [name, input, expected] of ok) {
    it(`${name}: ${JSON.stringify(input)} → ${expected}`, () => {
      expect(parseLocalizedNumber(input)).toBe(expected);
    });
  }

  const rejected: [string, unknown][] = [
    ['пустая строка', ''],
    ['только пробелы', '   '],
    ['текст', 'abc'],
    ['валюта в числе ($)', '$9.90'],
    ['валюта в числе (₴)', '100 ₴'],
    ['null', null],
    ['undefined', undefined],
    ['NaN', NaN],
    ['Infinity', Infinity],
    ['объект', {}],
    ['два десятичных разделителя', '1,2,3x'],
    ['неоднозначное 1,250 (может быть 1250 или 1,25)', '1,250'],
  ];

  for (const [name, input] of rejected) {
    it(`отклоняет: ${name}`, () => {
      expect(parseLocalizedNumber(input)).toBeNull();
    });
  }

  // Фиксируем текущее поведение: запятая с тремя цифрами отклоняется как неоднозначная,
  // а точка с тремя цифрами принимается как десятичная. Если решите это унифицировать,
  // этот тест подскажет, что поведение изменилось.
  it('асимметрия: "1.250" принимается как 1.25, а "1,250" отклоняется', () => {
    expect(parseLocalizedNumber('1.250')).toBe(1.25);
    expect(parseLocalizedNumber('1,250')).toBeNull();
  });
});
